"""Extract full-resolution hero frames from the source video.

The default WebP quality is 100 and frames keep the source video's native
dimensions. OpenCV is used only by this build-time utility; the app serves the
generated files as ordinary static assets from ``public/hero-frames``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import cv2


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("public/hero-video.mp4"),
        help="Source video path (default: public/hero-video.mp4)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("public/hero-frames"),
        help="Output directory (default: public/hero-frames)",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("src/data/heroFrames.ts"),
        help="Generated TypeScript frame manifest path",
    )
    parser.add_argument(
        "--quality",
        type=int,
        default=100,
        choices=range(1, 101),
        metavar="1-100",
        help="WebP quality; 100 preserves the highest practical quality",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not args.input.is_file():
        raise SystemExit(f"Input video not found: {args.input}")

    capture = cv2.VideoCapture(str(args.input))
    if not capture.isOpened():
        raise SystemExit(f"Unable to open input video: {args.input}")

    args.output.mkdir(parents=True, exist_ok=True)
    for old_frame in args.output.glob("frame-*.webp"):
        old_frame.unlink()

    fps = capture.get(cv2.CAP_PROP_FPS) or 0
    width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH) or 0)
    height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT) or 0)
    frame_paths: list[str] = []
    frame_number = 0

    try:
        while True:
            success, frame = capture.read()
            if not success:
                break

            frame_number += 1
            filename = f"frame-{frame_number:03d}.webp"
            encoded_success, encoded = cv2.imencode(
                ".webp",
                frame,
                [cv2.IMWRITE_WEBP_QUALITY, args.quality],
            )
            if not encoded_success:
                raise SystemExit(f"Unable to encode frame {frame_number}")

            (args.output / filename).write_bytes(encoded.tobytes())
            frame_paths.append(f"/hero-frames/{filename}")
    finally:
        capture.release()

    if not frame_paths:
        raise SystemExit("No frames were extracted from the input video")

    manifest = "// Generated by scripts/extract-hero-frames.py. Do not edit by hand.\n\n"
    manifest += f"export const HERO_FRAME_WIDTH = {width};\n"
    manifest += f"export const HERO_FRAME_HEIGHT = {height};\n"
    manifest += f"export const HERO_FRAME_FPS = {fps:g};\n"
    manifest += "export const HERO_FRAMES = [\n"
    manifest += "".join(f"  '{path}',\n" for path in frame_paths)
    manifest += "] as const;\n"
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(manifest, encoding="utf-8")

    print(
        f"Extracted {len(frame_paths)} frames at {width}x{height} "
        f"({fps:g} fps) to {args.output}"
    )


if __name__ == "__main__":
    main()
