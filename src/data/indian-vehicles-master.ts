export function getYearsForRange(yearFrom = 2008, yearTo = new Date().getFullYear() + 1): string[] {
  const maxYear = Math.max(yearFrom, yearTo);
  const years: string[] = [];
  for (let y = maxYear; y >= yearFrom; y--) {
    years.push(String(y));
  }
  return years;
}
